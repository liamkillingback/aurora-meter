            {module, fun, arity} = entry = function_entry!(row),
            module_present?(module),
            hidden?(module, fun, arity),
            do: {row.line, format_entry(entry)}

      assert offenders == [],
             "docs/api.md lists functions carrying @doc false:\n" <> lines(offenders)
    end

    test "the internal section and @internal_modules are the same list", %{regions: regions} do
      documented = regions |> rows(:internal) |> Enum.map(&module_entry!/1) |> Enum.sort()

