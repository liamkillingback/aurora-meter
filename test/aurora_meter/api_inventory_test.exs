      assert undocumented == [],
             "these must keep a real @doc:\n" <> lines(undocumented)
    end

    test "every internal module carries the stability banner" do
      banner = "**Internal.**"

      missing =
        for module <- @internal_modules,
            %{} = doc <- [moduledoc(module)],
