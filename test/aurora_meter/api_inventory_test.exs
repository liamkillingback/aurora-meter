defmodule AuroraMeter.ApiInventoryTest do
  @moduledoc """
  Guards the published API inventory in `docs/api.md`.

  Five unit-local invariants, named in build unit 02a:

    * A01: every `Module.function/arity` listed in `docs/api.md` exists at
      runtime, except rows tagged `optional-dep` whose module is absent.
    * A02: nothing internal (`@doc false`, or a module in `@internal_modules`)
      appears in `docs/api.md`.
    * A03: every non-internal module under `lib/` carries a real `@moduledoc`.
    * A04: every public function of a non-internal module carries a `@spec`,
      unless it is listed in `@spec_exceptions` with a reason.
    * A05: every telemetry event and PubSub tag documented in `docs/api.md`
      appears verbatim in `lib/`.

  The test reflects on compiled modules and reads `docs/api.md` as text. It
  touches no database and starts nothing, so it is `async: true`.

  `docs/api.md` is parsed by the HTML comments `<!-- inventory:<mode> -->`.
  Everything before the first one, and everything in an `inventory:none`
  region, is prose. Inside a region, the first row of each table is its header
  and every later row must carry a single inline-code span in its first cell.
  """
